        private readonly string _rootFolder;
        private readonly string _logoPath;
        private readonly ICurrentUserService _currentUserService;
        private readonly ICorrespondenceTemplateRepository _templateRepository;
        public DocumentService(IConfiguration configuration, ICurrentUserService currentUserService, ICorrespondenceTemplateRepository templateRepository)
        {
            _rootFolder = configuration["Documents:RootFolder"]!;
            _logoPath = configuration["Documents:LogoPath"]!;

            if (!Directory.Exists(_rootFolder))
                Directory.CreateDirectory(_rootFolder);

            _currentUserService = currentUserService;
            _templateRepository = templateRepository;
        }

        public async Task<DocumentResult> GenerateInstructionLetterAsync(
    SendInstructionLetterModel model,
    CancellationToken cancellationToken = default)
        {
            var template = await _templateRepository.GetActiveAsync(
                CorrespondenceTemplateType.InstructionLetter);

            if (template == null)
                throw new InvalidOperationException(
                    "The Instruction Letter template has not been configured.");

            var subject = ReplacePlaceholders(template.Subject, model, _currentUserService.FullName);
            var body = ReplacePlaceholders(template.Body, model, _currentUserService.FullName);

            var safeTender = model.TenderNumber
                .Replace("/", "-")
                .Replace("\\", "-");

            var fileName =
                $"Instruction_{safeTender}_{DateTime.UtcNow:yyyyMMddHHmmss}.pdf";

            var path = Path.Combine(_rootFolder, fileName);

            Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Margin(40);

                    page.Header()
                        .Column(column =>
                        {
                            column.Item()
                                .Height(45)
                                .Image("wwwroot/cidb-logo.png");

                            column.Item()
                                .Text("CIDB Regulatory Compliance Intelligence Platform (CRCIP)")
                                .FontSize(10)
                                .FontColor("#666666");

                            column.Item()
                                .PaddingTop(8)
                                .LineHorizontal(1)
                                .LineColor("#B3202A");
                        });


                    page.Content()
                        .PaddingTop(20)
                        .Column(column =>
                        {
                            column.Spacing(10);

                            column.Item()
                                .Text(body)
                                .FontSize(11);
                        });

                    page.Footer()
                        .AlignCenter()
                        .Text(text =>
                        {
                            text.Span("Generated by CIDB Regulatory Compliance Intelligence Platform (CRCIP) • Page ");
                            text.CurrentPageNumber();
                            text.Span(" of ");
                            text.TotalPages();
                        });
                });
            })
            .GeneratePdf(path);

            return new DocumentResult
            {
                FileName = fileName,
                FilePath = path
            };
        }

        public Task<DocumentResult> GenerateAgsaReferralDocumentAsync(
            AgsaReferralDocumentModel model,
            CancellationToken cancellationToken = default)
        {
            var safeTender = model.TenderNumber
                .Replace("/", "-")
                .Replace("\\", "-");

            var fileName =
                $"AGSAReferral_{safeTender}_{DateTime.UtcNow:yyyyMMddHHmmss}.pdf";

            var path = Path.Combine(_rootFolder, fileName);

            Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Margin(40);

                    page.Header()
                        .Row(row =>
                        {
                            var logo = File.Exists(_logoPath) ? _logoPath : null;

                            if (logo != null)
                                row.ConstantItem(120).Image(logo);

                            row.RelativeItem()
                                .Column(column =>
                                {
                                    column.Item()
                                        .Text("Referral for Enforcement")
                                        .FontSize(20)
                                        .Bold();

                                    column.Item()
                                        .Text($"Reference: {model.ReferralNumber}");
                                });
                        });

                    page.Content()
                        .PaddingTop(20)
                        .Column(column =>
                        {
                            column.Spacing(8);

                            column.Item().Text($"Tender Number: {model.TenderNumber}");
                            column.Item().Text($"Tender Title: {model.TenderTitle}");
                            column.Item().Text($"Employer: {model.EmployerName}");
                            column.Item().Text($"Referral Date: {model.ReferralDate:dd MMM yyyy}");
                            column.Item().PaddingTop(10).Text("Reason for Referral").Bold();
                            column.Item().Text(model.Reason);

                            if (!string.IsNullOrWhiteSpace(model.Description))
                            {
                                column.Item().PaddingTop(10).Text("Description").Bold();
                                column.Item().Text(model.Description);
                            }
                        });

                    page.Footer()
                        .AlignCenter()
                        .Text(text =>
                        {
                            text.Span("Generated by CIDB Regulatory Compliance Intelligence Platform (CRCIP) • Page ");
                            text.CurrentPageNumber();
                            text.Span(" of ");
                            text.TotalPages();
                        });
                });
            })
            .GeneratePdf(path);

            return Task.FromResult(new DocumentResult
            {
                FileName = fileName,
                FilePath = path
            });
        }

        private static string ReplacePlaceholders(string template, SendInstructionLetterModel model, string user)
        {
            return template
                .Replace("{CompanyName}", model.RecipientName)
                .Replace("{ContactPerson}", model.RecipientName)
                .Replace("{TenderNumber}", model.TenderNumber)
                .Replace("{TenderTitle}", model.TenderTitle)
                .Replace("{EmployerName}", model.EmployerName)
                .Replace("{ClosingDate}", model.ClosingDate.ToString("dd MMM yyyy"))
                .Replace("{ResponseDueDate}", model.ResponseDueOn.ToString("dd MMM yyyy"))
                .Replace("{AgentName}", user)
                .Replace("{FooterText}", model.FooterText ?? string.Empty)
                .Replace("{CurrentDate}", DateTime.Now.ToString("dd MMM yyyy"));
            // {Manager_Signature} is intentionally left unreplaced - it is the literal
            // anchor text SigningHub's autoplace API searches the PDF for.
        }

